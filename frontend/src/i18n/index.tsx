export const supportedLanguages = [
  { code: 'en' as Language, name: 'English', short: 'EN' },
  { code: 'es' as Language, name: 'Español', short: 'ES' },
  { code: 'pt-BR' as Language, name: 'Português', short: 'PT' },
];

function getBrowserLanguage(): Language {
  const browserLang = navigator.language;
  if (browserLang.startsWith('es')) return 'es';
  if (browserLang.startsWith('pt')) return 'pt-BR';
  return 'en';
}

function getStoredLanguage(): Language {
  const stored = localStorage.getItem('daicer-language') as Language;
  if (stored && (stored === 'en' || stored === 'es' || stored === 'pt-BR')) {
    return stored;
  }
  return getBrowserLanguage();
}

export function useI18n() {
  const [language, setLanguageState] = useState<Language>(getStoredLanguage());

  const setLanguage = (lang: Language) => {
    localStorage.setItem('daicer-language', lang);
    setLanguageState(lang);
  };

  const t = (key: string): string => {
    const keys = key.split('.');

    const findTranslation = (langObj: (typeof translations)[Language]): string | null => {
      let current: unknown = langObj;
      for (let index = 0; index < keys.length; index += 1) {
        const currentKey = keys[index];
        if (typeof currentKey !== 'string') {
          return null;
        }
        if (typeof current !== 'object' || current === null || !(currentKey in current)) {
          return null;
        }
        current = (current as Record<string, unknown>)[currentKey];
      }
      return typeof current === 'string' ? current : null;
    };

    // Try to get from selected language first
    if (language !== 'en') {
      const langData = translations[language];
      if (langData) {
        const val = findTranslation(langData);
        if (val) return val;
      }
    }

    // Fallback to English
    const fallback = findTranslation(translations.en);
    return fallback || key;
  };

  return {
    t,
    language,
    setLanguage,
    availableLanguages: supportedLanguages,
  };
}

